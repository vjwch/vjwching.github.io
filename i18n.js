function simp(v) {
  if (typeof v === 'string') return [...v].map(c => SIMP_MAP[c] || c).join('');
  if (Array.isArray(v)) return v.map(simp);
  if (v && typeof v === 'object') return Object.fromEntries(Object.entries(v).map(([k, x]) => [k, simp(x)]));
  return v;
}

